/**
 * Builds the browser module: src/styles/*.css inlined as one string and
 * src/client/*.js concatenated into src/client/index.template.js.
 * Run `node scripts/build.mjs` from the package directory; client.js is the
 * only shipped artifact and is generated, never edited by hand.
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const stylesUrl = new URL('src/styles/', root)
const clientUrl = new URL('src/client/', root)

const styles = readdirSync(stylesUrl).filter((file) => file.endsWith('.css')).sort()
if (!styles.length || styles[0] !== '00-palette.css') throw new Error('styles must start with 00-palette.css')

const modules = readdirSync(clientUrl).filter((file) => /^\d{2}-[a-z]+\.js$/.test(file)).sort()
if (!modules.length) throw new Error('no client modules found')

const cssChunks = styles.map((file) => readFileSync(new URL(file, stylesUrl), 'utf8').trim())
const css = cssChunks.join('\n\n')
const code = modules
  .map((file) => '/* ---- src/client/' + file + ' ---- */\n\n' + readFileSync(new URL(file, clientUrl), 'utf8').trim())
  .join('\n\n')

// One JS string per CSS line, grouped under a /* src/styles/<file> */ comment:
// client.js reads almost like the stylesheets it was built from, and editing one
// CSS line changes one line of the bundle instead of one 30 kB string literal.
const cssExpression = styles
  .flatMap((file, index) => {
    const lines = cssChunks[index].split('\n')
    const entries = ['      /* src/styles/' + file + ' */']
    lines.forEach((line, lineIndex) => {
      const tail = lineIndex < lines.length - 1 ? '\n' : index < styles.length - 1 ? '\n\n' : ''
      entries.push('      ' + JSON.stringify(line + tail) + ',')
    })
    return entries
  })
  .join('\n')

const banner = '/* Generated by scripts/build.mjs - edit src/styles/*.css or src/client/*.js instead. */\n'
const source = readFileSync(new URL('index.template.js', clientUrl), 'utf8')
  .replace('__THEME_CSS__', () => cssExpression)
  .replace('__CLIENT_CODE__', () => '\n' + code + '\n')

if (source.includes('__THEME_CSS__') || source.includes('__CLIENT_CODE__')) throw new Error('marker left in output')

writeFileSync(new URL('client.js', root), banner + source)
console.log('client.js written (' + (banner.length + source.length) + ' bytes) from ' + styles.length + ' stylesheets and ' + modules.length + ' modules')
